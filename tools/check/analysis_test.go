package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// The tracked hook must reject five nested controls while allowing ordinary
// four-level code, else-if chains and separate callbacks. Counting plain braces
// or ignoring function boundaries would reject valid changes or miss violations.
// No earlier Go gate analyzed nesting; these run its real file/parser boundary.
func TestSourceGateEnforcesNestingAndGeneratedBoundary(t *testing.T) {
	for _, fixture := range []struct {
		name, source string
		included     bool
		violation    bool
	}{
		{"four", "package fixture\nfunc f() { if true { for { switch { case true: select { default: } } } } }", true, false},
		{"five", "package fixture\nfunc f() { if true { for { switch { case true: select { default: if true {} } } } } }", true, true},
		{"else_if_chain", "package fixture\nfunc f() { if true {} else if true {} else if true {} else if true {} else if true {} }", true, false},
		{"callback_scope", "package fixture\nfunc f() { if true { for { switch { case true: select { default: _ = func() { if true { for { switch { case true: select { default: } } } } } } } } } }", true, false},
		{"generated", "// Code generated by fixture, DO NOT EDIT.\npackage fixture\nfunc f() { if true { for { switch { case true: select { default: if true {} } } } } }", false, false},
	} {
		t.Run(fixture.name, func(t *testing.T) {
			path := filepath.Join(t.TempDir(), "fixture.go")
			if err := os.WriteFile(path, []byte(fixture.source), 0600); err != nil {
				t.Fatal(err)
			}
			sources, err := analyzeSources([]string{path})
			if fixture.violation {
				if err == nil || !strings.Contains(err.Error(), "control nesting exceeds 4") {
					t.Fatalf("gate did not reject nested source: %v", err)
				}
				return
			}
			if err != nil || (len(sources) == 1) != fixture.included {
				t.Fatalf("gate source boundary: %v %v", sources, err)
			}
		})
	}
}
