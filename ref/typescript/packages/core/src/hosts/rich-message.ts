import { parseRichMarkdown, splitMarkdown, textLength } from '@relanox/markdown'
import type { RichMarkdownPart } from '@relanox/markdown'
import type {
  AgentAttachment,
  ChannelPlugin,
  DeliveryChunk,
  MediaReference,
  ReplyTarget,
  RichTextPart
} from '@relanox/sdk'
import { CoreError } from '../errors.js'

type MediaPart = {
  readonly type: 'media'
  readonly index: number
  readonly label: string
  readonly image: boolean
}

type MessagePart = Extract<RichMarkdownPart, { type: 'text' }> | MediaPart

export type RichMessage = {
  readonly parts: readonly MessagePart[]
  readonly attachments: readonly AgentAttachment[]
  readonly order: readonly number[]
}

/** Resolve positional references before generated bytes receive durable IDs. */
export function richMessage(
  text: string,
  supplied: readonly AgentAttachment[] = []
): RichMessage {
  const attachments = [...supplied]
  const used = new Set<number>()
  const parts: MessagePart[] = []
  for (const part of parseRichMarkdown(text)) {
    if (part.type === 'text') {
      parts.push(part)
      continue
    }
    let index: number
    if (part.reference.kind === 'attachment') {
      index = part.reference.index - 1
      if (index >= supplied.length) {
        throw new CoreError('invalid_media_reference')
      }
    } else {
      const id = part.reference.id
      index = attachments.indexOf(id)
      if (index === -1) {
        index = attachments.length
        attachments.push(id)
      }
    }
    if (used.has(index)) {
      throw new CoreError('duplicate_attachment')
    }
    used.add(index)
    parts.push({ type: 'media', index, label: part.label, image: part.image })
  }

  const remaining = attachments
    .map((_, index) => index)
    .filter((index) => !used.has(index))

  for (const index of remaining) {
    parts.push({ type: 'media', index, label: '', image: false })
  }
  return { parts, attachments, order: [...used, ...remaining] }
}

export function orderedReferences(
  message: RichMessage,
  references: readonly MediaReference[]
): readonly MediaReference[] {
  for (const part of message.parts) {
    if (
      part.type === 'media' &&
      part.image &&
      references[part.index]?.kind !== 'image'
    ) {
      throw new CoreError('invalid_image_reference')
    }
  }
  return message.order.map((index) => {
    const reference = references[index]
    if (!reference) {
      throw new CoreError('invalid_media_reference')
    }
    return reference
  })
}

function textChunks(
  plugin: ChannelPlugin<unknown>,
  text: string,
  target: ReplyTarget,
  rich = false
): readonly string[] {
  if (!text.trim()) {
    return []
  }

  const fragments =
    rich && plugin.capabilities.richText
      ? splitMarkdown(text, {
          maxLength: plugin.capabilities.richText.maxTextLength,
          unit: plugin.capabilities.lengthUnit
        })
      : [text]

  return fragments.flatMap(
    (fragment) =>
      plugin.splitText?.(fragment, target) ??
      splitMarkdown(fragment, {
        maxLength: plugin.capabilities.maxTextLength,
        unit: plugin.capabilities.lengthUnit
      })
  )
}

type ChunkContent = Pick<DeliveryChunk, 'text' | 'media' | 'richText'>

class ChunkBuilder {
  readonly chunks: ChunkContent[] = []

  private pending: RichTextPart[] = []

  private pendingLength = 0

  private pendingImageBytes = 0

  constructor(private readonly plugin: ChannelPlugin<unknown>) {}

  add(part: RichTextPart): void {
    const rich = this.plugin.capabilities.richText
    if (!rich) {
      this.chunks.push(
        part.type === 'text'
          ? { text: part.text }
          : { text: '', media: part.media }
      )
      return
    }

    const length =
      part.type === 'text'
        ? textLength(part.text, this.plugin.capabilities.lengthUnit)
        : 0

    const imageBytes = part.type === 'image' ? part.media.size : 0

    if (
      this.pending.length >= rich.maxParts ||
      this.pendingLength + length > rich.maxTextLength ||
      this.pendingImageBytes + imageBytes >
        (rich.maxTotalImageBytes ?? Infinity)
    ) {
      this.flush()
    }
    this.pending.push(part)
    this.pendingLength += length
    this.pendingImageBytes += imageBytes
  }

  media(reference: MediaReference): void {
    this.flush()
    this.chunks.push({ text: '', media: reference })
  }

  flush(): void {
    if (this.pending.some((part) => part.type === 'image')) {
      this.chunks.push({ text: '', richText: this.pending })
    } else {
      for (const part of this.pending) {
        if (part.type === 'text') {
          this.chunks.push({ text: part.text })
        }
      }
    }
    this.pending = []
    this.pendingLength = 0
    this.pendingImageBytes = 0
  }
}

function addMedia(
  builder: ChunkBuilder,
  part: MediaPart,
  reference: MediaReference,
  plugin: ChannelPlugin<unknown>,
  target: ReplyTarget
): void {
  if (part.image) {
    const rich = plugin.capabilities.richText
    if (
      rich &&
      ((rich.imageMimeTypes &&
        !rich.imageMimeTypes.includes(reference.mimeType)) ||
        reference.size >
          Math.min(
            rich.maxImageBytes ?? Infinity,
            rich.maxTotalImageBytes ?? Infinity
          ))
    ) {
      builder.media(reference)
      return
    }
    builder.add({
      type: 'image',
      media: reference,
      label: part.label || reference.fileName
    })
    return
  }
  if (part.label) {
    const label = part.label.replaceAll(
      /[\\`*_{}[\]()#+.!>~|=-]/gu,
      String.raw`\$&`
    )

    for (const fragment of textChunks(plugin, label, target, true)) {
      builder.add({ type: 'text', text: fragment })
    }
  }
  builder.media(reference)
}

/** Freeze the complete native delivery plan before any outbound effects. */
export function richChunks(
  plugin: ChannelPlugin<unknown>,
  deliveryId: string,
  message: RichMessage,
  references: readonly MediaReference[],
  target: ReplyTarget
): readonly DeliveryChunk[] {
  if (
    references.length >
      (plugin.capabilities.maxAttachmentsPerMessage ?? Infinity) ||
    references.some(
      (item) => !plugin.capabilities.media?.send.includes(item.kind)
    )
  ) {
    throw new CoreError('media_not_supported')
  }

  const visible = message.parts
    .map((part) => (part.type === 'text' ? part.text : part.label))
    .join('')

  if (
    textLength(visible, plugin.capabilities.lengthUnit) >
    (plugin.capabilities.maxTextLengthPerMessage ?? Infinity)
  ) {
    throw new CoreError('reply_exceeds_channel_limit')
  }
  const builder = new ChunkBuilder(plugin)
  for (const part of message.parts) {
    if (part.type === 'text') {
      for (const text of textChunks(plugin, part.text, target, true)) {
        builder.add({ type: 'text', text })
      }
      continue
    }
    const reference = references[part.index]
    if (!reference) {
      throw new CoreError('invalid_media_reference')
    }
    addMedia(builder, part, reference, plugin, target)
  }
  builder.flush()
  if (
    builder.chunks.length === 0 ||
    builder.chunks.length >
      (plugin.capabilities.maxChunksPerMessage ?? Infinity)
  ) {
    throw new CoreError('reply_exceeds_channel_limit')
  }
  const chunks: DeliveryChunk[] = []
  for (const [index, chunk] of builder.chunks.entries()) {
    chunks.push({
      ...chunk,
      idempotencyKey: `${deliveryId}:${index}`,
      state: null
    })
  }
  return chunks
}
