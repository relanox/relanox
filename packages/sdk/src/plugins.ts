import type { Json, SDK_MAJOR } from './values.js'
import type {
  ChannelId,
  AgentId,
  AccountConfig,
  EndpointConfig
} from './config.js'
import type {
  IngestInput,
  IngestReceipt,
  MessageReceipt,
  DispatchResult,
  SendResult,
  SendInput,
  ReplyTarget,
  DispatchInput
} from './messages.js'
import type { StateStore } from './state.js'
import type {
  ChannelAddress,
  ChannelResolution,
  AgentStatus
} from './conversations.js'
import type { Storage } from './storage.js'
import type { Observability } from './observability.js'
import type {
  AgentMediaHost,
  ChannelMediaHost,
  MediaKind,
  AgentAttachment
} from './media.js'

export type HttpHandler = (request: Request) => Promise<Response>

export type HttpRouteOptions = {
  readonly maxBodyBytes: number
  /** Reject unauthorized transfers before core reads a potentially large binary body. */
  authorize(request: Request): Promise<Response | undefined>
}

export type CommonHost = {
  /** The validated deployment origin; absent only when no public routes require it. */
  readonly publicUrl?: string
  readonly observe: Observability
  readonly state: StateStore
  /** Routes are plugin-scoped; OAuth well-known routes place the namespace after the metadata name (RFC 8414/9728). */
  mountHttp(
    path: string,
    handler: HttpHandler,
    options?: HttpRouteOptions
  ): void
  connection(
    status: 'connected' | 'disconnected' | 'degraded',
    errorCode?: string
  ): void
}

/** Core binds this host to a single validated account; plugins cannot choose the account scope. */
export type ChannelHost = {
  /** Isolated setup discovery only: report authenticated addresses instead of receiving content. */
  discoverConversation?(address: {
    readonly chatId: string
    readonly senderId: string
    readonly threadId?: string
  }): void
  /** Configured conversation IDs for this account, used by connection channels to subscribe. */
  readonly boundChatIds?: readonly string[]
  readonly maxMediaBytes?: number
  readonly media?: ChannelMediaHost
  ingest(input: IngestInput): Promise<IngestReceipt>
} & CommonHost

export type AgentPrincipal = {
  readonly subject: string
  readonly endpointIds: readonly string[]
}

/** Principal comes only from verified protocol authentication. Core intersects it with this plugin's configured endpoints. */
export type ScopedAgentHost = {
  readonly media?: AgentMediaHost
  status(input?: { readonly deliveryId?: string }): Promise<AgentStatus>
  sendMessage(input: {
    readonly channel: string
    readonly idempotencyKey?: string
    readonly text: string
    /** Existing channel media IDs or newly generated bytes, in delivery order. */
    readonly attachments?: readonly AgentAttachment[]
  }): Promise<MessageReceipt>
}

export type AgentHost = {
  forPrincipal(principal: AgentPrincipal): ScopedAgentHost
} & CommonHost

export type PluginMetadata = {
  readonly id: string
  readonly sdkMajor: typeof SDK_MAJOR
  readonly runtime: 'node'
}

export type Lifecycle = {
  start?(signal: AbortSignal): Promise<void>
  stop?(): Promise<void>
}

export type ChannelPlugin<C = Json> = {
  readonly kind: 'channel'
  readonly channel: ChannelId
  readonly capabilities: {
    readonly receive: true
    readonly transport: 'http' | 'connection' | 'both'
    readonly maxTextLength: number
    /** Aggregate source Markdown limit using lengthUnit, checked before enqueue. */
    readonly maxTextLengthPerMessage?: number
    readonly lengthUnit: 'utf16' | 'codepoint' | 'utf8'
    readonly idempotentSend: boolean
    /** Reject oversized replies before sending when a platform limits per-message calls. */
    readonly maxChunksPerMessage?: number
    readonly maxAttachmentsPerMessage?: number
    /** Ordered native text/image blocks; other media use sequential delivery. */
    readonly richText?: {
      readonly maxParts: number
      /** Aggregate source text per rich chunk, measured using lengthUnit. */
      readonly maxTextLength: number
      readonly imageMimeTypes?: readonly string[]
      readonly maxImageBytes?: number
    }
    readonly media?: {
      readonly receive: readonly MediaKind[]
      readonly send: readonly MediaKind[]
    }
  }
  validateConfig(config: unknown): C
  /** Resolve a configured conversation without requiring a triggering message. */
  resolveChannel?(
    address: ChannelAddress,
    learned?: ReplyTarget
  ): Promise<ChannelResolution>
  /** Split Markdown against rendered platform limits, retaining complete formatting. */
  splitText?(markdown: string, target: ReplyTarget): readonly string[]
  setup(host: ChannelHost, account: AccountConfig, config: C): Promise<void>
  send(input: SendInput): Promise<SendResult>
} & PluginMetadata &
  Lifecycle

export type AgentPlugin<C = Json> = {
  readonly kind: 'agent'
  readonly agent: AgentId
  validateConfig(config: unknown): C
  setup(
    host: AgentHost,
    endpoints: readonly EndpointConfig[],
    config: C
  ): Promise<void>
  dispatch(input: DispatchInput): Promise<DispatchResult>
} & PluginMetadata &
  Lifecycle

export type StoragePlugin<C = Json> = {
  readonly kind: 'storage'
  validateConfig(config: unknown): C
  setup(config: C, observe: Observability): Promise<Storage>
} & PluginMetadata

export type ObservabilityRuntime = {
  readonly observe: Observability
  readonly metrics?: HttpHandler
  flush(signal: AbortSignal): Promise<void>
  shutdown(signal: AbortSignal): Promise<void>
}

export type ObservabilityPlugin<C = Json> = {
  readonly kind: 'observability'
  validateConfig(config: unknown): C
  setup(config: C): Promise<ObservabilityRuntime>
} & PluginMetadata
