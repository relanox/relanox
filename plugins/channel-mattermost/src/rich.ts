import { textLength } from '@relanox/markdown'
import type { ChannelHost, SendInput, SendResult } from '@relanox/sdk'

export function richError(
  input: SendInput,
  host: ChannelHost
): string | undefined {
  const parts = input.chunk.richText
  if (!parts) {
    return undefined
  }
  if (!host.publicUrl || !host.media) {
    return 'public_media_unavailable'
  }
  if (
    parts.length > 20 ||
    textLength(
      parts
        .filter((part) => part.type === 'text')
        .map((part) => part.text)
        .join(''),
      'codepoint'
    ) > 8000
  ) {
    return 'rich_message_limit_exceeded'
  }
  const images = parts.filter((part) => part.type === 'image')
  if (
    images.length !== (input.richMedia?.length ?? 0) ||
    images.some(
      (part, index) => input.richMedia?.[index]?.reference.id !== part.media.id
    )
  ) {
    return 'missing_media'
  }
  if (
    (input.richMedia ?? []).some((media) => media.reference.kind !== 'image')
  ) {
    return 'media_limit_exceeded'
  }
  return undefined
}

export async function richMarkdown(
  input: SendInput,
  host: ChannelHost
): Promise<string | SendResult> {
  const pieces: string[] = []
  for (const part of input.chunk.richText ?? []) {
    if (part.type === 'text') {
      pieces.push(part.text)
    } else {
      if (!host.media) {
        throw new Error('public_media_unavailable')
      }

      const url = await host.media.publish({
        channelId: input.channelId,
        mediaId: part.media.id
      })

      const label = (part.label || part.media.fileName)
        .replaceAll(/[\\[\]]/gu, String.raw`\$&`)
        .replaceAll(/[\r\n]/gu, ' ')

      // The destination is generated by the scoped publication host, never Markdown input.
      pieces.push(`![${label}](<${url}>)`)
    }
  }
  const message = pieces.join('\n\n')
  if (textLength(message, 'codepoint') > 16_000) {
    return { status: 'rejected', errorCode: 'rich_message_limit_exceeded' }
  }
  return message
}
