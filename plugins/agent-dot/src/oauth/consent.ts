import { equalSecret } from '@relanox/agent-mcp'
import {
  digest,
  grantSchema,
  lifetime,
  OAuthError,
  oauthJson,
  opaque,
  pendingSchema,
  requestedScope,
  singleParameters
} from './protocol.js'
import type { Grant } from './protocol.js'
import type { OAuthStore } from './store.js'
import type { ClientRegistry } from './clients.js'

const escapeHtml = (value: string): string =>
  value.replaceAll(
    /[&<>"']/gu,
    (character) =>
      ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[
        character
      ] ?? character
  )

export function createConsent(
  store: OAuthStore,
  resource: string,
  issuer: string,
  secret: string,
  endpointId: string,
  clients: ClientRegistry
): {
  begin(request: Request): Promise<Response>
  finish(request: Request, form: URLSearchParams): Promise<Response>
} {
  const origin = new URL(resource).origin
  const cookieName = `__Host-relanox-oauth-${endpointId}`

  function validate(query: URLSearchParams): { grant: Grant; name: string } {
    singleParameters(query)
    if (
      query.get('response_type') !== 'code' ||
      query.get('code_challenge_method') !== 'S256'
    ) {
      throw new OAuthError('invalid_request')
    }
    const client = clients.resolve(query.get('client_id') ?? '')
    if (!client.redirect_uris.includes(query.get('redirect_uri') ?? '')) {
      throw new OAuthError('invalid_request')
    }
    if (query.get('resource') !== resource) {
      throw new OAuthError('invalid_target')
    }

    const grant = grantSchema.parse({
      clientId: client.client_id,
      redirectUri: query.get('redirect_uri'),
      resource,
      scope: requestedScope(query.get('scope')),
      challenge: query.get('code_challenge'),
      state: query.get('state') ?? ''
    })

    return { grant, name: client.client_name }
  }

  async function begin(request: Request): Promise<Response> {
    const { grant, name } = validate(new URL(request.url).searchParams)
    await store.capacity('pending')
    const csrf = opaque()

    const pending = await store.issue(
      'pending',
      { grant, csrf: digest(csrf), attempts: 0 },
      lifetime.pending
    )

    const html = `<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Connect to Relanox</title><body><main><h1>Connect to Relanox / 连接 Relanox</h1><p>${escapeHtml(name)} requests access to Agent <strong>${escapeHtml(endpointId)}</strong>.</p><p>Allow reading attachments, replying to this Agent's conversations and managing its message subscriptions.</p><p>允许读取附件、回复此 Agent 的聊天，并管理消息订阅。</p><form method="post" action="${escapeHtml(issuer)}/authorize"><input type="hidden" name="request" value="${pending}"><label for="password">Authorization password / 授权口令</label><p>Use the password generated by the configurator and set on your server.<br>输入配置器生成并已设置到服务器的授权口令。</p><input id="password" name="password" type="password" required autocomplete="current-password" autofocus><p><button name="decision" value="allow">Allow / 授权</button> <button name="decision" value="deny" formnovalidate>Cancel / 取消</button></p></form></main></body></html>`
    return new Response(html, {
      headers: {
        'Content-Type': 'text/html; charset=utf-8',
        'Cache-Control': 'no-store',
        'Referrer-Policy': 'no-referrer',
        'X-Content-Type-Options': 'nosniff',
        'Content-Security-Policy':
          "default-src 'none'; frame-ancestors 'none'; base-uri 'none'; form-action 'self' https://chatgpt.com",
        'Set-Cookie': `${cookieName}=${csrf}; Secure; HttpOnly; SameSite=Lax; Path=/; Max-Age=300`
      }
    })
  }

  function redirect(
    grant: Grant,
    parameter: 'code' | 'error',
    value: string
  ): Response {
    const url = new URL(grant.redirectUri)
    url.searchParams.set(parameter, value)
    url.searchParams.set('iss', issuer)
    if (grant.state) {
      url.searchParams.set('state', grant.state)
    }
    return new Response(null, {
      status: 303,
      headers: {
        Location: url.href,
        'Cache-Control': 'no-store',
        'Referrer-Policy': 'no-referrer',
        'Set-Cookie': `${cookieName}=; Secure; HttpOnly; SameSite=Lax; Path=/; Max-Age=0`
      }
    })
  }

  async function finish(
    request: Request,
    form: URLSearchParams
  ): Promise<Response> {
    const pending = await store.load(
      'pending',
      form.get('request') ?? '',
      pendingSchema
    )

    const cookie = request.headers
      .get('cookie')
      ?.split(';')
      .map((part) => part.trim())
      .find((part) => part.startsWith(`${cookieName}=`))
      ?.slice(cookieName.length + 1)

    if (
      request.headers.get('origin') !== origin ||
      !cookie ||
      !equalSecret(digest(cookie), pending.data.csrf)
    ) {
      throw new OAuthError('invalid_request', 403)
    }
    if (form.get('decision') === 'deny') {
      await store.consume(pending.entry)
      return redirect(pending.data.grant, 'error', 'access_denied')
    }
    if (form.get('decision') !== 'allow') {
      throw new OAuthError('invalid_request')
    }
    if (pending.data.attempts >= 10) {
      await store.consume(pending.entry)
      throw new OAuthError('access_denied', 403)
    }
    if (!equalSecret(form.get('password') ?? '', secret)) {
      await store.update(pending.entry, {
        ...pending.data,
        attempts: pending.data.attempts + 1
      })
      return oauthJson(
        {
          error: 'access_denied',
          error_description:
            'Incorrect authorization password. Go back and try again.'
        },
        403
      )
    }
    await store.consume(pending.entry)
    const code = await store.issue('code', pending.data.grant, lifetime.code)
    return redirect(pending.data.grant, 'code', code)
  }

  return { begin, finish }
}
